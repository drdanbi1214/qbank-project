-- =============================================================================
-- 완전 동일 문제 접기 설정
--
-- 같은 문제가 여러 학번 시험에 그대로 다시 나오면 이어풀기와 오답노트에 같은
-- 문제가 판본 수만큼 줄줄이 뜬다. 클러스터로 묶인 것 중 하나만 보여주는 것이
-- 기본이고, "그래도 다 풀어보고 싶다" 는 사람은 끌 수 있게 한다.
--
-- 기본값을 true 로 두는 이유: 묶기가 아직 없으면 아무 효과도 없고, 묶기가
-- 생기는 순간 원하는 동작이 바로 적용되는 편이 낫다.
-- =============================================================================

alter table public.profiles
  add column if not exists dedupe_identical boolean not null default true;

comment on column public.profiles.dedupe_identical is
  '완전 동일(identical)로 묶인 문제를 목록에서 하나만 보여줄지. 변주(modified)는 접지 않는다.';
